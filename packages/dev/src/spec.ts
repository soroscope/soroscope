import {
  generateContractArtifacts,
  parseWasmSpec,
  NoEmbeddedSpecError,
} from '@orbital-stellar/abi-registry';
import type {
  EventSpec,
  FunctionSpec,
  GeneratedContractArtifacts,
  ParsedWasmSpec,
  TypeSpec,
} from '@orbital-stellar/abi-registry';
import { scValToJs, type DiagnosticEvent, type ScVal } from '@soroscope/core';
import { contract } from '@stellar/stellar-sdk';

/**
 * A contract's interface, read from the `contractspecv0` section of its WASM.
 * Parsing and type generation come from Orbital's ABI registry
 * (`@orbital-stellar/abi-registry`); argument encoding from the Stellar SDK.
 */
export class ContractInterface {
  private constructor(
    readonly parsed: ParsedWasmSpec,
    private readonly sdkSpec: contract.Spec,
  ) {}

  /** @throws {NoEmbeddedSpecError} If the WASM has no embedded spec (stripped, or not built with soroban-sdk). */
  static fromWasm(wasm: Uint8Array): ContractInterface {
    const parsed = parseWasmSpec(wasm);
    return new ContractInterface(parsed, new contract.Spec(parsed.xdrEntries));
  }

  get functions(): readonly FunctionSpec[] {
    return this.parsed.functions;
  }

  get events(): readonly EventSpec[] {
    return this.parsed.events;
  }

  function(name: string): FunctionSpec | undefined {
    return this.parsed.functions.find((f) => f.name === name);
  }

  /**
   * Encode named arguments into base64 `ScVal`s in parameter order, using the
   * declared parameter types (so `"1000"` becomes an i128 where the spec says i128).
   * @throws {TypeError} If the function does not exist or an argument does not fit its type.
   */
  encodeArgs(fn: string, args: Record<string, unknown>): string[] {
    const spec = this.function(fn);
    if (spec === undefined) {
      throw new TypeError(
        `The contract has no function "${fn}". It has: ${this.parsed.functions.map((f) => f.name).join(', ')}.`,
      );
    }
    const missing = spec.params.filter((p) => !(p.name in args)).map((p) => p.name);
    if (missing.length > 0) {
      throw new TypeError(`${signature(spec)}: missing ${missing.join(', ')}.`);
    }
    const unknown = Object.keys(args).filter((k) => !spec.params.some((p) => p.name === k));
    if (unknown.length > 0) {
      throw new TypeError(`${signature(spec)}: no parameter named ${unknown.join(', ')}.`);
    }
    try {
      return this.sdkSpec.funcArgsToScVals(fn, args).map((v) => v.toXDR('base64'));
    } catch (err) {
      throw new TypeError(
        `${signature(spec)}: ${err instanceof Error ? err.message : String(err)}`,
      );
    }
  }

  /** Name an emitted event and its fields from the spec's `#[contractevent]` declarations. */
  nameEvent(event: DiagnosticEvent['event']): NamedEvent | null {
    const first = event.topics[0];
    if (first === undefined || first.type !== 'symbol') return null;
    const spec = this.parsed.events.find((e) => eventTopic(e) === first.value);
    if (spec === undefined) return null;
    const fields: Record<string, unknown> = {};
    // Topic 0 is the event-name prefix; the rest map to the declared topic fields in order.
    spec.topics.slice(1).forEach((f, i) => {
      const v = event.topics[i + 1];
      if (v !== undefined) fields[f.name] = scValToJs(v);
    });
    Object.assign(fields, dataFields(spec, event.data));
    return { name: spec.name, fields };
  }

  /** The `#[contracterror]` case with this code, as the contract names and documents it. */
  errorCase(code: number): { name: string; doc: string } | null {
    // At runtime the SDK returns plain {doc, name, value} records here, not the
    // XDR class its typings declare, so read them as such.
    const cases = this.sdkSpec.errorCases() as unknown as {
      doc: unknown;
      name: unknown;
      value: number;
    }[];
    const c = cases.find((e) => e.value === code);
    return c === undefined ? null : { name: String(c.name), doc: String(c.doc) };
  }

  /** TypeScript declarations, Zod schemas and event guards, generated by Orbital's codegen. */
  generateTypes(name: string): GeneratedContractArtifacts {
    return generateContractArtifacts({
      version: '0.0.0',
      name,
      functions: this.parsed.functions,
      events: this.parsed.events,
      types: this.parsed.types,
      xdrEntries: this.parsed.xdrEntries,
    });
  }
}

export { NoEmbeddedSpecError };

export interface NamedEvent {
  /** The event struct's name in the contract, e.g. `Moved`. */
  name: string;
  fields: Record<string, unknown>;
}

/** What changed between two versions of a contract's functions. */
export interface InterfaceDiff {
  added: string[];
  removed: string[];
  /** Same name, different parameters or return type. */
  changed: string[];
}

export function diffInterfaces(
  before: ContractInterface | null,
  after: ContractInterface,
): InterfaceDiff {
  const old = new Map((before?.functions ?? []).map((f) => [f.name, signature(f)]));
  const now = new Map(after.functions.map((f) => [f.name, signature(f)]));
  return {
    added: [...now.keys()].filter((n) => !old.has(n)).sort(),
    removed: [...old.keys()].filter((n) => !now.has(n)).sort(),
    changed: [...now.keys()].filter((n) => old.has(n) && old.get(n) !== now.get(n)).sort(),
  };
}

/** `move_funds(from: address, to: address, amount: i128) -> result<void, error>` */
export function signature(f: FunctionSpec): string {
  const ret = typeName(f.returns);
  return `${f.name}(${f.params.map((p) => `${p.name}: ${typeName(p.type)}`).join(', ')})${ret === 'void' ? '' : ` -> ${ret}`}`;
}

export function typeName(t: TypeSpec): string {
  if (typeof t === 'string') return t;
  switch (t.type) {
    case 'option':
      return `option<${typeName(t.inner)}>`;
    case 'result':
      return `result<${typeName(t.ok)}, ${typeName(t.err)}>`;
    case 'vec':
      return `vec<${typeName(t.item)}>`;
    case 'map':
      return `map<${typeName(t.key)}, ${typeName(t.value)}>`;
    case 'tuple':
      return `(${t.elements.map(typeName).join(', ')})`;
    case 'bytes_n':
      return `bytes_n<${t.size}>`;
    case 'named':
      return t.name;
  }
}

/** The symbol a `#[contractevent]` struct publishes as its first topic: its name in snake_case. */
function eventTopic(e: EventSpec): string {
  return e.name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();
}

function dataFields(spec: EventSpec, data: ScVal): Record<string, unknown> {
  if (spec.data.length === 0) return {};
  // Default data format is a map keyed by field name; `single-value` puts the one field there directly.
  if (data.type === 'map' && data.value !== null) {
    const out: Record<string, unknown> = {};
    for (const entry of data.value) {
      const key = scValToJs(entry.key);
      if (typeof key === 'string') out[key] = scValToJs(entry.val);
    }
    return out;
  }
  if (spec.data.length === 1) return { [spec.data[0]!.name]: scValToJs(data) };
  if (data.type === 'vec' && data.value !== null) {
    const items = data.value;
    return Object.fromEntries(
      spec.data.map((f, i) => {
        const item = items[i];
        return [f.name, item === undefined ? null : scValToJs(item)];
      }),
    );
  }
  return { data: scValToJs(data) };
}
